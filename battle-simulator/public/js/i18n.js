export function eraLabel(era) {
  return T.eras[era] || era;
}

export function typeLabel(type) {
  return T.types[type] || type.replace(/-/g, " ");
}

export function stateLabel(state) {
  return T.states[state] || state;
}

export function stageLabel(stage) {
  return T.stages[stage] || stage;
}

// 86000 -> "86,000" in English, "8.6万" in Chinese.
export function formatCount(n) {
  if (!n) return "?";
  if (LANG === "zh" && n >= 10000) return `${+(n / 10000).toFixed(n % 10000 ? 1 : 0)}万`;
  return n.toLocaleString("en-US");
}

export function yearLabel(year) {
  if (!year) return "";
  if (LANG === "zh") return year < 0 ? `公元前${-year}年` : `${year}年`;
  return year < 0 ? `${-year} BC` : `AD ${year}`;
}

function roman(n) {
  return ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII"][n - 1] || String(n);
}

function chineseNumeral(n) {
  return ["一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "十一", "十二"][n - 1] || String(n);
}

// Merges a translation overlay onto an original battle (or person).
// Objects merge by key and arrays by index; an array of strings laid over
// an array of labelled objects (map features, arrows) sets their labels;
// `units` and `figures` overlays are keyed by unit id and person id.
export function localize(base, overlay) {
  if (!overlay) return base;
  if (Array.isArray(base) && Array.isArray(overlay)) {
    if (base.length && typeof base[0] === "object" && overlay.every((o) => typeof o === "string")) {
      return base.map((b, i) => (overlay[i] === undefined ? b : { ...b, label: overlay[i] }));
    }
    if (overlay.every((o) => typeof o === "string")) return overlay;
    return base.map((b, i) => localize(b, overlay[i]));
  }
  if (base && typeof base === "object" && overlay && typeof overlay === "object") {
    const out = { ...base };
    for (const [k, v] of Object.entries(overlay)) {
      if ((k === "units" || k === "figures") && Array.isArray(base[k]) && !Array.isArray(v)) {
        const idKey = k === "units" ? "id" : "person";
        out[k] = base[k].map((item) => localize(item, v[item[idKey]]));
      } else if (k === "tags") {
        out.tags = [...(base.tags || []), ...v];
      } else {
        out[k] = k in base ? localize(base[k], v) : v;
      }
    }
    return out;
  }
  return overlay;
}
